#!/usr/bin/env python3
"""把 Apple II 字元 ROM 轉成 C 標頭檔給 KeyboardTester 用。

ROM 本身受著作權保護，不入版控（見專案根目錄 .gitignore），
產生出來的 apple2_char_rom.h 同樣不入版控 —— 它只是 ROM 的另一種編碼。

用法:
    python tools/rom2h.py <path-to-apple2_char.rom>

預設輸出到 KeyboardTester/apple2_char_rom.h（sketch 目錄）。
"""

import sys
from pathlib import Path

EXPECTED_SIZE = 2048


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 1

    src = Path(sys.argv[1])
    data = src.read_bytes()
    if len(data) != EXPECTED_SIZE:
        print(f"error: {src} is {len(data)} bytes, expected {EXPECTED_SIZE}")
        return 1

    out = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parent.parent / "KeyboardTester" / "apple2_char_rom.h"

    lines = [
        "// Generated by tools/rom2h.py -- do not edit, do not commit.",
        f"// Source: {src.name} ({len(data)} bytes)",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"static const uint8_t APPLE2_CHAR_ROM[{len(data)}] = {{",
    ]
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        lines.append("  " + " ".join(f"0x{b:02X}," for b in chunk))
    lines.append("};")
    lines.append("")

    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out} ({len(data)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
